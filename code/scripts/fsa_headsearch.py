"""Random search over the NFSM head sizes on the algebraic tasks (free arm).

    python scripts/fsa_headsearch.py sample      # results/fsa_headsearch/configs.json
    python scripts/fsa_headsearch.py commands    # one line per run
    python scripts/fsa_headsearch.py table       # results/fsa_headsearch/summary.md

1 to 5 heads of 2 to 16 states, drawn without looking at the task; 15 draws per task (seed 42),
split between configurations that can or cannot represent the task (one-layer NFSM correct at every
length). Reference rows: the paper head sizes, seeds 42-46. Defaults otherwise.
"""

import argparse
import itertools
import json
import os
import sys

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.environ.get("HEADSEARCH_DIR", os.path.join(ROOT, "results", "fsa_headsearch"))
TASKS = ("S3", "S4", "Z2", "FF", "Z16")
N, SAMPLE_SEED, SEED = 15, 0, 42
H_MAX, N_MIN, N_MAX = 5, 2, 16
STRATA = {"S3": (10, 5), "S4": (10, 5), "Z2": (15, 0), "FF": (14, 1), "Z16": (10, 5)}   # (representable, not)
REF = {"S3": "factored", "S4": "factored", "Z2": "regular", "FF": "regular", "Z16": "regular"}
REF_HEADS = {"S3": (3, 2), "S4": (4, 3, 2), "Z2": (2,), "FF": (3,), "Z16": (16,)}
REF_SEEDS = (42, 43, 44, 45, 46)
LENS = (64, 256, 1024, 4096, 16384)


# ---- representability ---------------------------------------------------------------------------

def _compose(p, q):
    return tuple(p[q[i]] for i in range(len(q)))


def _closure(gens, e):
    out, frontier = {e}, [e]
    while frontier:
        nxt = []
        for x in frontier:
            for g in gens:
                y = _compose(x, g)
                if y not in out:
                    out.add(y)
                    nxt.append(y)
        frontier = nxt
    return frozenset(out)


def subgroups(k: int) -> list:
    """Every subgroup of S_k (k <= 4: all are generated by at most two elements)."""
    elems = list(itertools.permutations(range(k)))
    e = tuple(range(k))
    return sorted({_closure(pair, e) for pair in itertools.combinations_with_replacement(elems, 2)},
                  key=len)


def group_representable(k: int, heads) -> bool:
    """Subgroups K_i of index <= n_i with trivial intersection (K_i = G leaves head i unused)."""
    subs = subgroups(k)
    order = len(subs[-1])
    options = [[K for K in subs if order // len(K) <= n] for n in heads]
    for choice in itertools.product(*options):
        if len(frozenset.intersection(*choice)) == 1:
            return True
    return False


def representable(task: str, heads) -> bool:
    if task in ("Z2", "Z16"):          # subgroups of Z_{2^k} form a chain: one head must hold all 2^k
        return max(heads) >= int(task[1:])
    if task == "FF":
        return max(heads) >= 3 or len(heads) >= 2
    return group_representable({"S3": 3, "S4": 4}[task], heads)


# ---- sampling -----------------------------------------------------------------------------------

def rung(heads) -> str:
    return "h" + "-".join(map(str, heads))


def sample() -> list:
    rng = np.random.default_rng(SAMPLE_SEED)
    cfgs = []
    for task in TASKS:
        want = dict(zip((True, False), STRATA[task]))
        seen, kept = set(), {True: [], False: []}
        for _ in range(200_000):
            if all(len(kept[r]) == want[r] for r in want):
                break
            heads = tuple(int(n) for n in rng.integers(N_MIN, N_MAX + 1, rng.integers(1, H_MAX + 1)))
            key = tuple(sorted(heads))
            if key in seen:
                continue
            seen.add(key)
            r = representable(task, heads)
            if len(kept[r]) < want[r]:
                kept[r].append(heads)
        else:
            raise RuntimeError(f"{task}: strata not filled")
        for r in (True, False):
            for heads in kept[r]:
                cfgs.append({"task": task, "heads": list(heads), "representable": r,
                             "token": f"{task},{rung(heads)},nfsm,1,free,{SEED}"})
    for task in TASKS:
        for s in REF_SEEDS:
            cfgs.append({"task": task, "heads": list(REF_HEADS[task]), "representable": True,
                         "reference": True, "token": f"{task},{REF[task]},nfsm,1,free,{s}"})
    return cfgs


def load_configs() -> list:
    with open(os.path.join(OUT, "configs.json")) as f:
        return json.load(f)["configs"]


def name(token: str) -> str:
    return token.replace(",", "_")


def part(token: str):
    p = os.path.join(OUT, "fsa", "parts", name(token) + ".json")
    if not os.path.exists(p):
        return None
    with open(p) as f:
        return json.load(f)


# ---- table --------------------------------------------------------------------------------------

def table() -> str:
    cfgs = load_configs()
    head = ("| task | heads | H | states | theory | " + " | ".join(f"T={L}" for L in LENS)
            + " | exact | steps | min |")
    lines = ["# NFSM head-size search: sequence accuracy (%), free arm, one layer", "",
             head, "|---|---|---:|---:|---|" + "---:|" * (len(LENS) + 3)]
    for c in cfgs:
        r = part(c["token"])
        tag = f"**paper** (seed {c['token'].rsplit(',', 1)[1]})" if c.get("reference") else ""
        pre = (f"| {c['task']} | ({', '.join(map(str, c['heads']))}) {tag} | {len(c['heads'])} | "
               f"{sum(c['heads'])} | {'yes' if c['representable'] else 'no'} | ")
        if r is None:
            lines.append(pre + " | ".join("-" for _ in LENS) + " | - | - | not finished |")
            continue
        acc = dict(zip(r["lens"], r["seq_acc"]))
        ext = r.get("extraction") or {}
        h = r.get("history") or {}
        lines.append(pre + " | ".join(f"{100 * acc[L]:.1f}" if L in acc else "-" for L in LENS)
                     + f" | {'yes' if ext.get('exact') else 'no'} | {h.get('steps_run')}"
                     f" | {r.get('train_seconds', 0) / 60:.1f} |")
    lines += ["", "theory: whether some NFSM with these heads tracks the task at every length "
              "(scripts/fsa_headsearch.py). exact: the extracted machine is correct at every length."]
    text = "\n".join(lines) + "\n"
    with open(os.path.join(OUT, "summary.md"), "w") as f:
        f.write(text)
    print(text)
    return text


def main():
    p = argparse.ArgumentParser()
    p.add_argument("action", choices=("sample", "commands", "table"))
    a = p.parse_args()
    if a.action == "sample":
        os.makedirs(OUT, exist_ok=True)
        cfgs = sample()
        with open(os.path.join(OUT, "configs.json"), "w") as f:
            json.dump({"sampling_seed": SAMPLE_SEED, "lens": LENS,
                       "space": {"H": f"uniform {{1..{H_MAX}}}", "n_i": f"uniform {{{N_MIN}..{N_MAX}}}"},
                       "strata": STRATA, "configs": cfgs}, f, indent=1)
        for c in cfgs:
            print(c["task"], c["heads"], "representable" if c["representable"] else "NOT",
                  "(paper)" if c.get("reference") else "")
    elif a.action == "commands":
        lens = " ".join(map(str, LENS))
        for c in load_configs():
            print(f"{name(c['token'])}\t-m experiments.fsa.run --job {c['token']} "
                  f"--sweep-lens {lens} --no-wandb")
    else:
        table()


if __name__ == "__main__":
    sys.exit(main())
